class TestAgent(BaseAgent):
    """Writes test files and runs them using pytest.

    State keys read:
        phase     – must be "test" to activate
        code_path – path to the generated source file
        test_path – path to the test file (set by this agent after writing)

    State keys written (via returned action or state mutation):
        phase     – set to "review" on pass, "fix" on failure
        test_path – path to the generated test file
    """

    # Prevent pytest from attempting to collect this class as a test suite.
    __test__ = False

    _WRITE  = "writing_tests"
    _RUN    = "running_tests"

    def __init__(self, output_dir: str) -> None:
        super().__init__(
            name="TestAgent",
            role="test_runner",
            model_name="mock",
            tools=["write_file", "run_tests"],
        )
        self.output_dir = output_dir

    def can_act(self, task: Task, state: dict[str, Any]) -> bool:
        return state.get("phase") == "test"

    def act(self, task: Task, state: dict[str, Any]) -> Action:
        sub_phase = state.get("test_sub_phase", self._WRITE)

        if sub_phase == self._WRITE:
            test_path = os.path.join(self.output_dir, "test_stack.py")
            state["test_path"] = test_path
            state["test_sub_phase"] = self._RUN

            return Action(
                type="tool_call",
                tool_name="write_file",
                tool_input={"path": test_path, "content": _STACK_TESTS},
                message="Writing test file",
            )

        # sub_phase == _RUN
        test_path = state["test_path"]
        last_result = state.get("last_tool_result", {})

        # Check if we just finished running tests
        if state.get("tests_ran"):
            success = last_result.get("success", False)
            if success:
                state["phase"] = "review"
            else:
                state["phase"] = "fix"
                state["test_results"] = last_result.get("output", "")
                state["test_sub_phase"] = self._WRITE  # reset for next iteration
            state["tests_ran"] = False
            # Yield control to next agent by returning a message
            return Action(
                type="message",
                message="Tests complete" if success else "Tests failed – handing off to CodeAgent for a fix",
            )

        # First time in _RUN sub-phase: trigger the test runner
        state["tests_ran"] = True
        return Action(
            type="tool_call",
            tool_name="run_tests",
            tool_input={"path": test_path},
            message="Running tests",
        )


