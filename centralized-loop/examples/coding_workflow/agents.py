class ReviewAgent(BaseAgent):
    """Performs a lightweight code-quality review.

    In v1 this is a stub: it checks that the code file exists and is
    non-empty, then marks the task done.

    State keys read:
        phase     – must be "review"
        code_path – path to the source file
    """

    def __init__(self) -> None:
        super().__init__(
            name="ReviewAgent",
            role="reviewer",
            model_name="mock",
            tools=["read_file"],
        )

    def can_act(self, task: Task, state: dict[str, Any]) -> bool:
        return state.get("phase") == "review"

    def act(self, task: Task, state: dict[str, Any]) -> Action:
        code_path = state.get("code_path", "")
        review_done = state.get("review_done", False)

        if not review_done:
            # Read the code for review
            state["review_done"] = True
            return Action(
                type="tool_call",
                tool_name="read_file",
                tool_input={"path": code_path},
                message="Reading code for review",
            )

        # Review complete – signal done
        last_result = state.get("last_tool_result", {})
        code_content = last_result.get("output", "")
        notes = self._review(code_content)
        return Action(
            type="done",
            message=f"Code review passed. Notes: {notes}",
        )

    def _review(self, code: str) -> str:
        """Very lightweight heuristic review (stub for v1)."""
        checks: list[str] = []
        if "class " in code:
            checks.append("defines a class")
        if "def " in code:
            checks.append("has methods")
        if '"""' in code or "'''" in code:
            checks.append("has docstrings")
        if checks:
            return "OK – " + ", ".join(checks)
        return "OK"
