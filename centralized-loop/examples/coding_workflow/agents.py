class CodeAgent(BaseAgent):
    """Generates (and re-generates on failure) source-code files.

    State keys read:
        phase (str)        – current workflow phase
        iteration (int)    – number of fix iterations so far
        test_results (str) – last pytest output (used to guide fixes)

    State keys written (via returned action):
        phase              – set to "test" after code is written
    """

    def __init__(self, output_dir: str) -> None:
        super().__init__(
            name="CodeAgent",
            role="code_generator",
            model_name="mock",
            tools=["write_file"],
        )
        self.output_dir = output_dir

    def can_act(self, task: Task, state: dict[str, Any]) -> bool:
        return state.get("phase") in {None, "code", "fix"}

    def act(self, task: Task, state: dict[str, Any]) -> Action:
        phase = state.get("phase", "code")
        iteration = state.get("iteration", 0)

        code = self._generate_code(task.goal, state)
        code_path = os.path.join(self.output_dir, "stack.py")

        # After writing the code, signal the engine to move to the test phase.
        state["phase"] = "test"
        state["code_path"] = code_path
        state["iteration"] = iteration + 1

        return Action(
            type="tool_call",
            tool_name="write_file",
            tool_input={"path": code_path, "content": code},
            message=f"Writing code (iteration {iteration + 1})",
        )

    def _generate_code(self, goal: str, state: dict[str, Any]) -> str:
        """Return source code for the goal.

        In v1 this returns a hardcoded stack implementation.  In a real
        system this would call an LLM API with the goal and any failure
        feedback from previous iterations.
        """
        return _STACK_IMPLEMENTATION


